"""Webots PROTO and ROS URDF of the prototype, from the CAD (tools/build_proto_cad.py: constants,
cad/parts.json masses + centre of mass, ros/wcr_proto/meshes/meshes.json coloured meshes).

  python tools/build_proto_webots.py -> webots/protos/WcrProto.proto, ros/wcr_proto/resource/wcr_proto.urdf

Robot frame (base_link) = the WHEEL CONTACT PLANE (the wall), like the dam sim's Wcr robot, so the
same spawn poses work: x forward (L298N end), y left, z away from the wall. The CAD frame (board
wall-side face) is 7.5 mm above it.
Physics: rigid body + 4 wheel hinges (N20, 60 rpm, 0.2 N m). The propeller is a kinematic visual
hinge; its thrust is applied by the driver plugin as a force at the hub (wcr_proto/proto_driver.py).
Device and frame names follow the dam sim (lidar, wall_camera, front_camera, imu ...), so its
inspection detector, wall frames, coverage mission and Foxglove layout work unchanged.
"""
import json
import math
from pathlib import Path

import build_proto_cad as C

ROOT = Path(__file__).resolve().parents[1]
MESH_DIR = ROOT / 'ros' / 'wcr_proto' / 'meshes'
BZ = (C.WHEEL_D / 2 - C.AXLE_Z) / 1000          # CAD frame -> base frame: +7.5 mm
WHEEL_R = C.WHEEL_D / 2000
WHEEL_MASS = C.MASS['wheel'] / 1000
N20_RPM, N20_TORQUE = 60.0, 0.2                 # no-load speed, rated torque (~2 kg cm) [N m]
PROTO_MESH = '../../ros/wcr_proto/meshes'       # relative to webots/protos


def m(v):
    return v / 1000.0


def base(p):
    """CAD point (mm) -> base frame (m)."""
    return (m(p[0]), m(p[1]), m(p[2]) + BZ)


def f(*v):
    return ' '.join(f'{x:.5f}' for x in v)


def wheels():
    """name -> (x, y) of the wheel centre in the base frame (z = wheel radius)."""
    return {n: (m(x), side * m(C.WHEEL_OUT_Y - C.WHEEL_W / 2)) for n, x, side in C.corners()}


def sensors():
    lx, ly, lz = base(C.LIDAR_AT)
    return dict(lidar=(lx, ly, lz), wall_camera=base(C.WALL_CAM_AT), front_camera=base(C.FRONT_CAM_AT),
                imu=base((C.IMU_AT[0], C.IMU_AT[1], C.IMU_AT[2] + 4)), prop=(0.0, 0.0, m(C.PROP_Z) + BZ))


def body_inertia(mass, lx=0.29, ly=0.20, lz=0.05):
    return (mass * (ly ** 2 + lz ** 2) / 12, mass * (lx ** 2 + lz ** 2) / 12, mass * (lx ** 2 + ly ** 2) / 12)


# ---------------------------------------------------------------- Webots
def shapes(index, stem, indent):
    out = []
    for e in index[stem]:
        r, g, b = e['color']
        rough, metal = (0.35, 0.8) if max(r, g, b) - min(r, g, b) < 0.05 and r > 0.6 else (0.6, 0.1)
        out.append(f'{indent}Shape {{ appearance PBRAppearance {{ baseColor {r:.3f} {g:.3f} {b:.3f} '
                   f'roughness {rough} metalness {metal} }} geometry Mesh {{ url "{PROTO_MESH}/{e["file"]}.obj" }} }}')
    return '\n'.join(out)


def proto(index, parts):
    s = sensors()
    total = parts['total_mass_g'] / 1000
    body_mass = total - 4 * WHEEL_MASS
    cx, cy, cz = base(parts['centre_of_mass_mm'])
    ixx, iyy, izz = body_inertia(body_mass)
    w_max = 3 * N20_RPM * 2 * math.pi / 60      # 3 x 60 rpm: room for speed:= demos; the driver keeps 60 rpm by default
    wcx, wcy, wcz = s['wall_camera']
    pitch = math.radians(C.WALL_CAM_PITCH)
    out = [f"""#VRML_SIM R2025a utf8
# Generated by tools/build_proto_webots.py - the PHYSICAL WCR prototype (foam board, A2212 1000 KV + 1045
# prop for thrust adhesion, 4 x N20 skid steer) with the sensor kit of the autonomous twin.
# base frame = wheel contact plane (the wall); x forward (L298N end), y left, z away from the wall.
# Mass {total * 1000:.0f} g ({parts['hardware_mass_g']:.0f} g hardware, measured {parts['measured_mass_g']} g, + {parts['sensor_kit_mass_g']:.0f} g sensor kit).
# The propeller thrust is applied by the controller (supervisor) as a force at the hub along -z.
PROTO WcrProto [
  field SFVec3f    translation    0 0 0
  field SFRotation rotation       0 0 1 0
  field SFString   name           "wcr"
  field SFString   controller     "<extern>"
  field MFString   controllerArgs []
  field SFBool     supervisor     TRUE
]
{{
  Robot {{
    translation IS translation
    rotation IS rotation
    name IS name
    controller IS controller
    controllerArgs IS controllerArgs
    supervisor IS supervisor
    children [
      Pose {{
        translation 0 0 {BZ:.5f}
        children [
          Transform {{ scale 0.001 0.001 0.001 children [
{shapes(index, 'body', '            ')}
          ] }}
        ]
      }}
      # propeller: kinematic visual rotor (no Physics); the thrust is the controller's force
      HingeJoint {{
        jointParameters HingeJointParameters {{ axis 0 0 1 anchor {f(*s['prop'])} }}
        device [
          RotationalMotor {{ name "prop_motor" maxVelocity 200 maxTorque 10 }}
          PositionSensor {{ name "prop_sensor" }}
        ]
        endPoint Solid {{
          translation {f(*s['prop'])}
          name "prop_link"
          children [ Transform {{ scale 0.001 0.001 0.001 children [
{shapes(index, 'prop', '            ')}
          ] }} ]
        }}
      }}"""]
    for n, (x, y) in wheels().items():
        rot = '0 0 1 3.141593' if y < 0 else '0 0 1 0'
        out.append(f"""      HingeJoint {{
        jointParameters HingeJointParameters {{ axis 0 1 0 anchor {f(x, y, WHEEL_R)} }}
        device [
          RotationalMotor {{ name "{n}_wheel" maxTorque {N20_TORQUE} maxVelocity {w_max:.4f} }}
          PositionSensor {{ name "{n}_wheel_sensor" }}
        ]
        endPoint Solid {{
          translation {f(x, y, WHEEL_R)}
          name "{n}_wheel_link"
          contactMaterial "proto_wheel"
          children [ Transform {{ rotation {rot} scale 0.001 0.001 0.001 children [
{shapes(index, 'wheel', '            ')}
          ] }} ]
          boundingObject Pose {{ rotation 1 0 0 1.5708 children [ Cylinder {{ height {m(C.WHEEL_W):.4f} radius {WHEEL_R:.4f} subdivision 32 }} ] }}
          # mass of the real wheel; inertia raised (x10) for a stable 8 ms physics step
          physics Physics {{ density -1 mass {WHEEL_MASS:.3f} centerOfMass [0 0 0] inertiaMatrix [2e-05 3e-05 2e-05, 0 0 0] }}
        }}
      }}""")
    out.append(f"""      InertialUnit {{ name "imu" translation {f(*s['imu'])} }}
      Gyro {{ name "gyro" translation {f(*s['imu'])} }}
      Accelerometer {{ name "accelerometer" translation {f(*s['imu'])} }}
      Lidar {{
        name "lidar"
        translation {f(*s['lidar'])}
        horizontalResolution 360
        fieldOfView 6.2832
        numberOfLayers 1
        verticalFieldOfView 0.05
        near 0.02
        minRange 0.05
        maxRange 12.0
        type "fixed"
        noise 0.001
        defaultFrequency 10
      }}
      Camera {{
        name "wall_camera"
        translation {f(wcx, wcy, wcz)}
        rotation 0 1 0 {pitch:.5f}
        fieldOfView 1.15
        width 640
        height 480
        near 0.01
        noise 0.01
      }}
      SpotLight {{
        location {f(wcx, wcy, wcz + 0.01)}
        direction {math.cos(pitch):.4f} 0.0000 {-math.sin(pitch):.4f}
        intensity 0.008
        attenuation 0 0 1
        beamWidth 0.6
        cutOffAngle 0.8
        castShadows FALSE
      }}
      Camera {{
        name "front_camera"
        translation {f(*s['front_camera'])}
        fieldOfView 1.3962634
        width 640
        height 480
        near 0.02
      }}
    ]
    boundingObject Group {{ children [
      Pose {{ translation 0 0 {BZ + m(C.BOARD_T) / 2:.5f} children [ Box {{ size {m(C.BOARD_L):.3f} {m(C.BOARD_W):.3f} {m(C.BOARD_T):.3f} }} ] }}
      Pose {{ translation 0 0 {BZ + m(C.BOARD_T) + 0.015:.5f} children [ Box {{ size 0.26 0.14 0.03 }} ] }}
    ] }}
    physics Physics {{
      density -1
      mass {body_mass:.4f}
      centerOfMass [ {cx:.4f} {cy:.4f} {cz:.4f} ]
      inertiaMatrix [ {ixx:.6f} {iyy:.6f} {izz:.6f}, 0 0 0 ]
    }}
  }}
}}
""")
    return '\n'.join(out)


# ---------------------------------------------------------------- URDF (robot_state_publisher, Foxglove)
def urdf(index):
    s = sensors()
    mats, link_vis = {}, {}
    for stem in ('body', 'wheel', 'prop'):
        vis = []
        for e in index[stem]:
            name = 'c_' + '_'.join(f'{int(v * 255):02x}' for v in e['color'])
            mats[name] = e['color']
            vis.append((e['file'], name))
        link_vis[stem] = vis

    def visuals(stem, xyz='0 0 0', rpy='0 0 0'):
        return ''.join(f'<visual><origin xyz="{xyz}" rpy="{rpy}"/><geometry><mesh filename="package://wcr_proto/meshes/'
                       f'{fn}.stl" scale="0.001 0.001 0.001"/></geometry><material name="{mat}"/></visual>'
                       for fn, mat in link_vis[stem])

    def joint(name, typ, parent, child, xyz, rpy=(0, 0, 0), axis=None):
        a = f'<axis xyz="{axis}"/>' if axis else ''
        return (f'<joint name="{name}" type="{typ}"><parent link="{parent}"/><child link="{child}"/>'
                f'<origin xyz="{f(*xyz)}" rpy="{f(*rpy)}"/>{a}</joint>\n')

    out = ['<?xml version="1.0"?>\n<!-- Generated by tools/build_proto_webots.py: the WCR prototype (base_link = wall '
           'contact plane). Visual only; physics lives in webots/protos/WcrProto.proto. -->\n<robot name="wcr">\n']
    out += [f'<material name="{n}"><color rgba="{c[0]:.3f} {c[1]:.3f} {c[2]:.3f} 1"/></material>\n' for n, c in mats.items()]
    out.append(f'<link name="base_link">{visuals("body", f"0 0 {BZ:.5f}")}</link>\n')
    out.append('<link name="prop_link">' + visuals('prop') + '</link>\n')
    # continuous: the driver publishes a slow DISPLAY angle (a rotor at ~900 rad/s would only strobe
    # in RViz / Foxglove at 50 Hz); Webots spins its own visual rotor
    out.append(joint('prop_joint', 'continuous', 'base_link', 'prop_link', s['prop'], axis='0 0 1'))
    for n, (x, y) in wheels().items():
        out.append(f'<link name="{n}_wheel_link">' + visuals('wheel', rpy='0 0 3.14159' if y < 0 else '0 0 0') + '</link>\n')
        out.append(joint(f'{n}_wheel_joint', 'continuous', 'base_link', f'{n}_wheel_link', (x, y, WHEEL_R), axis='0 1 0'))
    for name in ('lidar_link', 'imu_link', 'wall_camera_link', 'wall_camera_optical', 'front_camera_link',
                 'front_camera_optical'):
        out.append(f'<link name="{name}"/>\n')
    opt = (-math.pi / 2, 0, -math.pi / 2)
    out.append(joint('lidar_joint', 'fixed', 'base_link', 'lidar_link', s['lidar']))
    out.append(joint('imu_joint', 'fixed', 'base_link', 'imu_link', s['imu']))
    out.append(joint('wall_camera_joint', 'fixed', 'base_link', 'wall_camera_link', s['wall_camera'],
                     (0, math.radians(C.WALL_CAM_PITCH), 0)))
    out.append(joint('wall_camera_optical_joint', 'fixed', 'wall_camera_link', 'wall_camera_optical', (0, 0, 0), opt))
    out.append(joint('front_camera_joint', 'fixed', 'base_link', 'front_camera_link', s['front_camera']))
    out.append(joint('front_camera_optical_joint', 'fixed', 'front_camera_link', 'front_camera_optical', (0, 0, 0), opt))
    out.append('</robot>\n')
    return ''.join(out)


def main():
    index = json.loads((MESH_DIR / 'meshes.json').read_text())
    parts = json.loads((ROOT / 'cad' / 'parts.json').read_text())
    p = ROOT / 'webots' / 'protos' / 'WcrProto.proto'
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(proto(index, parts))
    u = ROOT / 'ros' / 'wcr_proto' / 'resource' / 'wcr_proto.urdf'
    u.parent.mkdir(parents=True, exist_ok=True)
    u.write_text(urdf(index))
    print(f'{p}\n{u}')
    for k, v in sensors().items():
        print(f'  {k:13s} {f(*v)}')


if __name__ == '__main__':
    main()
